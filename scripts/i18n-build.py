"""Builds WordPress translation files for the 'lereng' text domain from data/i18n/id_ID.json.

Writes the PHP format WordPress 6.5+ loads natively (lereng-id_ID.l10n.php) into the plugin's
languages folder, and lists strings in the code that have no translation yet.
Run: python3 scripts/i18n-build.py"""
import json, pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from importlib import import_module
extract = import_module('i18n-extract')
ROOT = pathlib.Path(__file__).resolve().parent.parent
tr = json.loads((ROOT / 'data/i18n/id_ID.json').read_text())
missing = [s for s in extract.strings() if s not in tr]
def php(s): return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"
# Plural pairs (_n singular/plural) share one entry: "singular\0plural" => "form0\0form1".
src = '\n'.join(p.read_text() for p in (ROOT / 'wp-content').glob('**/lereng*/**/*.php') if 'vendor' not in p.parts)
pairs = re.findall(r"\b_n\(\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'", src)
messages = dict(tr)
for one, many in pairs:
    one, many = (x.replace("\\'", "'") for x in (one, many))
    if one in tr and many in tr:
        messages[one + '\0' + many] = tr[one] + '\0' + tr[many]
out = ROOT / 'wp-content/plugins/lereng-commerce/languages/lereng-id_ID.l10n.php'
out.write_text("<?php\n// Generated by scripts/i18n-build.py from data/i18n/id_ID.json. Do not edit.\nreturn ['domain' => 'lereng', 'language' => 'id_ID', 'plural-forms' => 'nplurals=1; plural=0;', 'messages' => [\n"
               + ',\n'.join(f"  {php(k)} => {php(v)}".replace('\0', "' . \"\\0\" . '") for k, v in sorted(messages.items())) + "\n]];\n")
print(f'{len(messages)} messages → {out.relative_to(ROOT)}')
if missing:
    print(f'{len(missing)} without a translation:'); [print('  ' + m) for m in missing]
    sys.exit(1)
